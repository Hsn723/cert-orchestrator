const (
	certificateSetIndex = ".metadata.annotations.certificate-set"
)

var (
	errCanonicalNotOwned = errors.New("canonical Secret already exists and is not owned by the CertificateSet")
)

// SecretReconciler copies the active Secret of a CertificateSet to the canonical Secret.

type SecretReconciler struct {
	client.Client
	Scheme   *runtime.Scheme
	Recorder recorder.EventRecorder
}

// +kubebuilder:rbac:groups="",resources=secrets,verbs=get;list;watch;create;update;patch
// +kubebuilder:rbac:groups="",resources=events,verbs=create;patch
// +kubebuilder:rbac:groups=cert-orchestrator.atelierhsn.com,resources=certificatesets,verbs=get;list;watch

// Reconcile is part of the main kubernetes reconciliation loop which aims to
// move the current state of the cluster closer to the desired state.
func (r *SecretReconciler) Reconcile(ctx context.Context, req ctrl.Request) (ctrl.Result, error) {
	logger := logf.FromContext(ctx)

	secret := &corev1.Secret{}
	if err := r.Get(ctx, req.NamespacedName, secret); err != nil {
		return ctrl.Result{}, client.IgnoreNotFound(err)
	}

	setName := secret.Annotations[apiv1.CertificateSetNameAnnotation]
	if setName == "" {
		return ctrl.Result{}, nil
	}
	if !isActive(secret) {
		return ctrl.Result{}, nil
	}

	cs := &apiv1.CertificateSet{}
	if err := r.Get(ctx, client.ObjectKey{Namespace: req.Namespace, Name: setName}, cs); err != nil {
		if apierrors.IsNotFound(err) {
			logger.Info("CertificateSet not found, ignoring active Secret", "secret", secret.Name, "certificateSet", setName)
			return ctrl.Result{}, nil
		}
		return ctrl.Result{}, err
	}
	if !cs.DeletionTimestamp.IsZero() {
		logger.Info("CertificateSet is being deleted, ignoring active Secret", "secret", secret.Name, "certificateSet", setName)
		return ctrl.Result{}, nil
	}

	if !isMemberSecret(cs, secret.Name) {
		msg := fmt.Sprintf("Secret %q is annotated as active but is not generated by the CertificateSet %q, ignoring", secret.Name, setName)
		logger.Info(msg)
		r.Recorder.Eventf(secret, cs, corev1.EventTypeWarning, "ForeignActiveSecret", "SecretSync", msg)
		return ctrl.Result{}, nil
	}

	activeSecrets, err := r.activeSecretNames(ctx, cs)
	if err != nil {
		return ctrl.Result{}, err
	}
	if len(activeSecrets) > 1 {
		// Not retried: removing the extra annotation produces an event that reconciles the remaining active Secret.
		msg := fmt.Sprintf("multiple Secrets are annotated as active, not syncing: %s", strings.Join(activeSecrets, ", "))
		logger.Info(msg, "certificateSet", cs.Name)
		r.Recorder.Eventf(secret, cs, corev1.EventTypeWarning, "MultipleActiveSecrets", "SecretSync", msg)
		return ctrl.Result{}, nil
	}

	result, err := r.syncCanonical(ctx, cs, secret)
	if err != nil {
		reason := "SyncFailed"
		if errors.Is(err, errCanonicalNotOwned) {
			reason = "CanonicalConflict"
		}
		logger.Error(err, "failed to sync canonical Secret", "name", cs.Name)
		r.Recorder.Eventf(secret, cs, corev1.EventTypeWarning, reason, "SecretSync", err.Error())
		return ctrl.Result{}, err
	}
	if result != controllerutil.OperationResultNone {
		logger.Info("synced canonical Secret", "name", cs.Name, "operation", result)
		r.Recorder.Eventf(secret, cs, corev1.EventTypeNormal, "Synced", "SecretSync", "Synced Secret %q from %q", cs.Name, secret.Name)
	}

	return ctrl.Result{}, nil
}

func (r *SecretReconciler) activeSecretNames(ctx context.Context, cs *apiv1.CertificateSet) ([]string, error) {
	secrets := &corev1.SecretList{}
	listOpts := []client.ListOption{
		client.InNamespace(cs.Namespace),
		client.MatchingFields{certificateSetIndex: cs.Name},
	}
	if err := r.List(ctx, secrets, listOpts...); err != nil {
		return nil, err
	}
	var actives []string
	for i := range secrets.Items {
		if isActive(&secrets.Items[i]) {
			actives = append(actives, secrets.Items[i].Name)
		}
	}
	slices.Sort(actives)
	return actives, nil
}

func (r *SecretReconciler) syncCanonical(ctx context.Context, cs *apiv1.CertificateSet, src *corev1.Secret) (controllerutil.OperationResult, error) {
	target := &corev1.Secret{
		ObjectMeta: v1.ObjectMeta{
			Name:      cs.Name,
			Namespace: cs.Namespace,
		},
	}
	return controllerutil.CreateOrUpdate(ctx, r.Client, target, func() error {
		exists := target.ResourceVersion != ""
		if exists && !v1.IsControlledBy(target, cs) {
			return fmt.Errorf("%w: %s", errCanonicalNotOwned, target.Name)
		}
		if err := controllerutil.SetControllerReference(cs, target, r.Scheme); err != nil {
			return err
		}
		if !exists {
			// Secret.Type is immutable.
			target.Type = src.Type
			if target.Type == "" {
				target.Type = corev1.SecretTypeTLS
			}
		}
		if target.Labels == nil {
			target.Labels = map[string]string{}
		}
		target.Labels[managedByLabel] = managedByValue
		if target.Annotations == nil {
			target.Annotations = map[string]string{}
		}
		target.Annotations[apiv1.CertificateSetNameAnnotation] = cs.Name
		target.Data = maps.Clone(src.Data)
		return nil
	})
}

func isMemberSecret(cs *apiv1.CertificateSet, secretName string) bool {
	for _, t := range cs.Targets() {
		if t.Name == secretName {
			return true
		}
	}
	return false
}

// SetupWithManager sets up the controller with the Manager.
func (r *SecretReconciler) SetupWithManager(ctx context.Context, mgr ctrl.Manager) error {
	err := mgr.GetFieldIndexer().IndexField(ctx, &corev1.Secret{}, certificateSetIndex, func(rawObj client.Object) []string {
		cs := rawObj.GetAnnotations()[apiv1.CertificateSetNameAnnotation]
		if cs == "" {
			return nil
		}
		return []string{cs}
	})
	if err != nil {
		return err
	}
	relatedToSet := predicate.NewPredicateFuncs(func(o client.Object) bool {
		return certificateSetNameFor(o) != ""
	})
	return ctrl.NewControllerManagedBy(mgr).
		Named("secret").
		Watches(&corev1.Secret{}, handler.EnqueueRequestsFromMapFunc(r.findActiveSecrets), builder.WithPredicates(relatedToSet)).
		Complete(r)
}

func (r *SecretReconciler) findActiveSecrets(ctx context.Context, obj client.Object) []reconcile.Request {
	logger := logf.FromContext(ctx)
	setName := certificateSetNameFor(obj)
	if setName == "" {
		return nil
	}
	secrets := &corev1.SecretList{}
	listOpts := []client.ListOption{
		client.InNamespace(obj.GetNamespace()),
		client.MatchingFields{certificateSetIndex: setName},
	}
	if err := r.List(ctx, secrets, listOpts...); err != nil {
		logger.Error(err, "failed to list Secrets for CertificateSet", "certificateSet", setName)
		return nil
	}
	var requests []reconcile.Request
	for i := range secrets.Items {
		if isActive(&secrets.Items[i]) {
			requests = append(requests, reconcile.Request{
				NamespacedName: client.ObjectKeyFromObject(&secrets.Items[i]),
			})
		}
	}
	return requests
}
